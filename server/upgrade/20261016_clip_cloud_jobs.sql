CREATE TABLE IF NOT EXISTS `la_oem_clip_cloud_job` (
 `id` bigint unsigned NOT NULL AUTO_INCREMENT,
 `tenant_id` int unsigned NOT NULL,
 `user_id` int unsigned NOT NULL,
 `project_id` bigint unsigned NOT NULL,
 `plan_id` bigint unsigned NOT NULL DEFAULT 0,
 `revision` int unsigned NOT NULL,
 `operation` varchar(16) NOT NULL,
 `request_key` char(64) NOT NULL,
 `client_token` char(36) NOT NULL,
 `state` varchar(20) NOT NULL DEFAULT 'queued',
 `provider_id` varchar(160) NOT NULL DEFAULT '',
 `config_json` text NOT NULL,
 `input_json` mediumtext NOT NULL,
 `output_key` varchar(500) NOT NULL DEFAULT '',
 `result_json` mediumtext NOT NULL,
 `error` varchar(255) NOT NULL DEFAULT '',
 `lease_token` char(32) NOT NULL DEFAULT '',
 `lease_until` int unsigned NOT NULL DEFAULT 0,
 `next_poll` int unsigned NOT NULL DEFAULT 0,
 `create_time` int unsigned NOT NULL,
 `update_time` int unsigned NOT NULL,
 PRIMARY KEY (`id`),
 UNIQUE KEY `owned_request` (`tenant_id`,`user_id`,`request_key`),
 KEY `owner_jobs` (`tenant_id`,`user_id`,`project_id`,`id`),
 KEY `worker_queue` (`state`,`next_poll`,`lease_until`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
