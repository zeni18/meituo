CREATE TABLE IF NOT EXISTS `la_oem_clip_voice` (
 `id` bigint unsigned NOT NULL AUTO_INCREMENT,
 `tenant_id` int unsigned NOT NULL,
 `user_id` int unsigned NOT NULL,
 `name` varchar(80) NOT NULL,
 `request_key` varchar(64) NOT NULL,
 `custom_id` varchar(160) NOT NULL,
 `speaker_id` varchar(160) NOT NULL DEFAULT '',
 `config_signature` char(64) NOT NULL,
 `sample_hash` char(64) NOT NULL,
 `sample_path` varchar(300) NOT NULL,
 `sample_format` varchar(8) NOT NULL,
 `duration` decimal(8,3) NOT NULL,
 `state` varchar(20) NOT NULL DEFAULT 'queued',
 `preview_url` text NOT NULL,
 `preview_expires` int unsigned NOT NULL DEFAULT 0,
 `trial_expires` int unsigned NOT NULL DEFAULT 0,
 `activated_at` int unsigned NOT NULL DEFAULT 0,
 `consent_version` varchar(40) NOT NULL,
 `consent_time` int unsigned NOT NULL,
 `error` varchar(255) NOT NULL DEFAULT '',
 `lease_token` char(32) NOT NULL DEFAULT '',
 `lease_until` int unsigned NOT NULL DEFAULT 0,
 `next_poll` int unsigned NOT NULL DEFAULT 0,
 `create_time` int unsigned NOT NULL,
 `update_time` int unsigned NOT NULL,
 PRIMARY KEY (`id`),
 UNIQUE KEY `owned_request` (`tenant_id`,`user_id`,`request_key`),
 UNIQUE KEY `cloud_custom_id` (`custom_id`),
 KEY `owned_voices` (`tenant_id`,`user_id`,`id`),
 KEY `worker_queue` (`state`,`next_poll`,`lease_until`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
